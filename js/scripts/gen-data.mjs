// Embeds the shared ../data JSON into src/data.generated.ts so the package
// works in Node, Deno, bundlers and browsers without file-system access.
import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { dirname, join, relative, sep } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const dataDir = join(here, "..", "..", "data");

function collect(kind) {
  const base = join(dataDir, kind);
  const out = {};
  const walk = (dir) => {
    const entries = readdirSync(dir, { withFileTypes: true }).sort((a, b) => (a.name < b.name ? -1 : a.name > b.name ? 1 : 0));
    for (const entry of entries) {
      const { name } = entry;
      const path = join(dir, name);
      if (entry.isDirectory()) walk(path);
      else if (entry.isFile() && name.endsWith(".json") && !name.startsWith("_")) {
        const id = relative(base, path).slice(0, -5).split(sep).join("/");
        out[id] = JSON.parse(readFileSync(path, "utf8"));
      }
    }
  };
  try {
    walk(base);
  } catch (err) {
    if (err.code !== "ENOENT") throw err;
  }
  return out;
}

const messages = JSON.parse(readFileSync(join(dataDir, "i18n", "messages.json"), "utf8"));
const source = `// Generated by scripts/gen-data.mjs from /data. Do not edit.
/* eslint-disable */
export const CALENDARS: Record<string, unknown> = ${JSON.stringify(collect("calendars"))};
export const RULEPACKS: Record<string, unknown> = ${JSON.stringify(collect("rulepacks"))};
export const MESSAGES = ${JSON.stringify(messages)} as const;
`;
writeFileSync(join(here, "..", "src", "data.generated.ts"), source);
